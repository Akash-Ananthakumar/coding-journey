a = int(input("Enter a: "))
b = int(input("Enter b: "))

#Arithmetic Operators
print("Sum:", a + b)
print("Difference:", a - b)
print("Product:", a * b)
print("Quotient:", a / b)
print("Remainder:", a % b)
print("Exponentiation:", a ** b)
print("Floor Division:", a // b)
print("Absolute Value of a:", abs(a))
print("Absolute Value of b:", abs(b))
print("Maximum of a and b:", max(a, b))
print("Minimum of a and b:", min(a, b))
print("Round of a:", round(a))
print("Round of b:", round(b))
print("Square Root of a:", a ** 0.5)
print(round(a ** 0.5, 2))
print("Square Root of b:", b ** 0.5)
print(round(b ** 0.5, 2))
print("Power of a raised to b:", pow(a, b))
print("Power of b raised to a:", pow(b, a))

#Comparison Operators
print("a is equal to b:", a == b)
print("a is not equal to b:", a != b)
print("a is greater than b:", a > b)
print("a is less than b:", a < b)
print("a is greater than or equal to b:", a >= b)
print("a is less than or equal to b:", a <= b)

#Assignment Operators
a += b  # Equivalent to a = a + b
a -= b  # Equivalent to a = a - b
a *= b  # Equivalent to a = a * b
a /= b  # Equivalent to a = a / b
a %= b  # Equivalent to a = a % b
a **= b  # Equivalent to a = a ** b
a //= b  # Equivalent to a = a // b
